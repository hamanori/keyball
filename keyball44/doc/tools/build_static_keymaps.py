def remap_layer_refs(keycode: str, offset: int) -> str:
    """Move LT/MO/TG layer references into a profile-specific layer bank."""

    def replace(match: re.Match[str]) -> str:
        return f"{match.group(1)}({int(match.group(2)) + offset},"

    keycode = keycode.replace("KC_LANG1", "KC_LNG1").replace("KC_LANG2", "KC_LNG2")
    return re.sub(r"\b(LT|LM)\((\d+),", replace, keycode)


def format_layer(name: str, keys: list[str]) -> str:
    if len(keys) != 44:
        raise ValueError(f"{name}: expected 44 keys, got {len(keys)}")
    lines = [f"  [{name}] = LAYOUT_right_ball("]
    for row in range(3):
        start = row * 12
        left = ", ".join(keys[start:start + 6])
        right = ", ".join(keys[start + 6:start + 12])
        lines.append(f"    {left},    {right},")
    lines.append("    " + ", ".join(keys[36:41]) + ",    " + ", ".join(keys[41:44]))
    lines.append("  ),")
    return "\n".join(lines)


def main() -> None:
    mac = json.loads(MAC_SOURCE.read_text())
    win = json.loads(WIN_SOURCE.read_text())

    mac["keymap"] = "macos_reconstructed"
    mac["version"] = 2
    mac["layers"][1] = MAC_NAV
    mac["layers"][2] = MAC_SYMBOL
    mac["layers"][3] = MAC_SCROLL
    mac["notes"] = (
        "Reconstructed from the old Mac JSON, the 2026-07-18 17:11 Remap PDF, "
        "and the later Layer 1 screenshots. Cmd+Space and unknown Any keys are "
        "not invented; unresolved positions remain transparent. Layer 6 K uses "
        "User 5 for hold-scroll in the mouse-session specification."
    )
    MAC_OUTPUT.write_text(json.dumps(mac, ensure_ascii=False, indent=4) + "\n")

    layer_specs: list[tuple[str, list[str]]] = [
        ("L_MAC_BASE", [remap_layer_refs(key, 0) for key in mac["layers"][0]]),
        ("L_MAC_NAV", mac["layers"][1]),
        ("L_MAC_SYMBOL", mac["layers"][2]),
        ("L_MAC_SCROLL", mac["layers"][3]),
    ]
    for index, name in enumerate(
        ["L_WIN_BASE", "L_WIN_NAV", "L_WIN_SYMBOL", "L_WIN_SCROLL", "L_WIN_SHIFT"]
    ):
        layer_specs.append((name, [remap_layer_refs(key, 4) for key in win["layers"][index]]))

    mouse = [TRNS] * 44
    mouse[19] = "KC_MY_BTN1"
    mouse[20] = "KC_MY_SCR"
    mouse[21] = "KC_MY_BTN2"
    mouse[31] = "KC_MY_BTN4"
    mouse[33] = "KC_MY_BTN5"
    layer_specs.append(("L_MOUSE", mouse))

    output = [
        "// Generated by keyball44/doc/tools/build_static_keymaps.py.",
        "// Edit the JSON/reconstruction script instead of this file.",
        "const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {",
    ]
    output.extend(format_layer(name, keys) for name, keys in layer_specs)
    output.append("};\n")
    KEYMAP_OUTPUT.write_text("\n\n".join(output))
    print(f"wrote {MAC_OUTPUT}")
    print(f"wrote {KEYMAP_OUTPUT}")


if __name__ == "__main__":
    main()
