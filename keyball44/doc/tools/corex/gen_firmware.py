"""Generate the static keymaps and combos for the hamanori_corex keymap.

usage: gen_firmware.py MAC_SPEC.json WINDOWS_VIA_BACKUP.json OUT.inc
Windows layers 0-6 are copied verbatim from the Remap (VIA) EEPROM backup.
Mac layers 7-11 come from the CoreX port spec.
"""
import json, sys

spec = json.load(open(sys.argv[1]))
win = json.load(open(sys.argv[2]))
OUT = sys.argv[3]
ROWS, COLS = 8, 6
assert (win['rows'], win['cols'], win['layers']) == (ROWS, COLS, 7), 'unexpected Windows backup shape'

lines = ['// Generated by gen_firmware.py from the CoreX port spec and the Windows Remap backup.',
         '// Edit the spec or the generator instead of this file.', '',
         '// clang-format off',
         'const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {']


def emit(layer, grid, names):
    lines.append('  [%d] = {' % layer)
    for r in range(ROWS):
        cells = ', '.join('0x%04X' % grid[r][c] for c in range(COLS))
        lines.append('    {%s},  // %s' % (cells, ' | '.join(names[r])))
    lines.append('  },')


for L in range(7):
    grid = win['keymap'][L]
    emit(L, grid, [['' for _ in range(COLS)] for _ in range(ROWS)])

for name, lid in sorted(spec['layerIds'].items(), key=lambda kv: kv[1]):
    keys = spec['layers'][name]
    grid = [[0] * COLS for _ in range(ROWS)]
    labels = [[''] * COLS for _ in range(ROWS)]
    for p, k in keys.items():
        r, c = map(int, p.split(','))
        grid[r][c] = k['code']
        labels[r][c] = k['label'] or '.'
    lines.append('  // %s' % spec['layerInfo'][name][0])
    emit(lid, grid, labels)
lines += ['};', '// clang-format on', '']

ported = [c for c in spec['combos'] if c['ported']]
for i, cb in enumerate(ported):
    a, b = cb['keys']
    lines.append('const uint16_t PROGMEM corex_combo_%d[] = {0x%04X, 0x%04X, COMBO_END};  // %s' % (i, a, b, cb['symbol']))
lines.append('combo_t key_combos[] = {')
for i, cb in enumerate(ported):
    lines.append('  COMBO(corex_combo_%d, 0x%04X),' % (i, cb['output']))
lines.append('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', OUT, 'combos', len(ported))
